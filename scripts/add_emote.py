"""Validate an upload and atomically commit its texture and addon registry."""
import base64
import io
import json
import re
import tempfile
import warnings
from pathlib import Path

from PIL import Image
import requests

from scripts.sync_discord import convert

MAX_BYTES = 8 * 1024 * 1024


class ImportFailure(RuntimeError):
    """A locally constructed message safe to show without exposing HTTP data."""


def prepare(name, data):
    if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]{0,31}', name):
        raise ValueError('Use 1–32 letters, numbers or underscores, starting with a letter.')
    if not data or len(data) > MAX_BYTES:
        raise ValueError('Upload an image smaller than 8 MiB.')
    with warnings.catch_warnings():
        warnings.simplefilter('error', Image.DecompressionBombWarning)
        with Image.open(io.BytesIO(data)) as image:
            if image.format not in ('PNG', 'GIF', 'WEBP', 'JPEG'):
                raise ValueError('Supported formats: PNG, GIF, WebP and JPEG.')
            frames = getattr(image, 'n_frames', 1)
            if image.width * image.height > 4_000_000 or frames > 300 or image.width * image.height * frames > 32_000_000:
                raise ValueError('Image is too large or has too many animation frames.')
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / 'emote.tga'
            meta = convert(data, path)
            return path.read_bytes(), meta


def render(entries):
    lines = ['-- Generated by the Discord /addemote bot.', 'local category = {}']
    for name, meta in sorted(entries.items()):
        key = meta.get('trigger', f':uploaded_{name}:')
        texture = f'Interface\\AddOns\\LizzieEmotes\\Emotes\\uploaded\\{name}.tga'
        lines += [f'TwitchEmotes_defaultpack[{json.dumps(key)}] = {json.dumps(texture + ":28:28")}',
                  f'TwitchEmotes_emoticons[{json.dumps(key)}] = {json.dumps(key)}']
        if meta['nFrames'] > 1:
            fields = ', '.join(f'{k} = {v}' for k, v in meta.items() if k != 'trigger')
            lines.append(f'TwitchEmotes_animation_metadata[{json.dumps(texture)}] = {{{fields}}}')
        lines += [f'category[#category + 1] = {json.dumps(key)}',
                  'if #category == 45 then',
                  '    TwitchEmotes_dropdown_options[#TwitchEmotes_dropdown_options + 1] = category',
                  '    category = {}', 'end']
    lines += ['if #category > 0 then',
              '    TwitchEmotes_dropdown_options[#TwitchEmotes_dropdown_options + 1] = category', 'end', '']
    return '\n'.join(lines).encode()


class Publisher:
    def __init__(self, repository, branch, token):
        if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository):
            raise ValueError('Invalid GITHUB_REPOSITORY')
        if not re.fullmatch(r'[A-Za-z0-9_./-]+', branch):
            raise ValueError('Invalid GITHUB_BRANCH')
        self.base = f'https://api.github.com/repos/{repository}'
        self.branch = branch
        self.session = requests.Session()
        self.session.headers.update(Authorization=f'Bearer {token}', Accept='application/vnd.github+json',
                                    **{'X-GitHub-Api-Version': '2022-11-28'})

    def api(self, method, path, **kwargs):
        try:
            response = self.session.request(method, self.base + path, timeout=60, **kwargs)
        except requests.RequestException:
            raise ImportFailure('Cannot reach GitHub or the request timed out. Check GitHub before retrying.') from None
        if not response.ok:
            hints = {
                401: 'GitHub token is invalid or expired.',
                403: 'GitHub denied access. Check token repository access and Contents read/write permission (Actions read/write for releases), branch rules, and API rate limits.',
                404: 'GitHub could not find the repository, branch or resource, or your token cannot access it. Check GITHUB_REPOSITORY, GITHUB_BRANCH and token repository access.',
                409: 'GitHub reported a conflict. Check whether the branch changed, then retry.',
                422: 'GitHub rejected the update. Check branch protection, concurrent commits and repository settings.',
                429: 'GitHub rate limit reached. Wait before retrying.',
            }
            hint = hints.get(response.status_code, 'GitHub request failed. Check Actions/repository status before retrying.')
            raise ImportFailure(f'GitHub HTTP {response.status_code}: {hint}')
        return response.json() if response.content else {}

    def release_beta(self, flavor='Retail'):
        from scripts.package_addon import FLAVORS
        if flavor not in FLAVORS:
            raise ValueError('Invalid WoW client')
        result = self.api('POST', '/actions/workflows/release.yml/dispatches', json={
            'ref': self.branch,
            'inputs': {'sync_discord': False, 'publish': True,
                       'flavor': flavor, 'release_type': 'beta'}})
        return result.get('html_url', self.base.replace('api.github.com/repos/', 'github.com/')
                          + '/actions/workflows/release.yml')

    def publish(self, name, data, edit=False):
        texture, meta = prepare(name, data)
        head = self.api('GET', f'/git/ref/heads/{self.branch}')['object']['sha']
        commit = self.api('GET', f'/git/commits/{head}')
        tree = self.api('GET', f'/git/trees/{commit["tree"]["sha"]}')
        manifest = next((item for item in tree['tree'] if item['path'] == 'UploadedEmotes.json'), None)
        entries = {}
        if manifest:
            blob = self.api('GET', f'/git/blobs/{manifest["sha"]}')
            entries = json.loads(base64.b64decode(blob['content']))
        existing = next((key for key in entries if key.casefold() == name.casefold()), None)
        if edit and existing is None:
            raise ValueError('No uploaded emote with that name exists. Use /addemote first.')
        if not edit and existing is not None:
            raise ValueError('That upload name already exists. Choose another name.')
        if edit:
            # Keep the original filename and trigger, including legacy names.
            name = existing
            if 'trigger' in entries[name]:
                meta['trigger'] = entries[name]['trigger']
        else:
            meta['trigger'] = name
            # Avoid shadowing emotes bundled in the original addon packs.
            for item in tree['tree']:
                if item['path'] not in ('Emotes.lua', 'DiscordEmotes.lua'):
                    continue
                blob = self.api('GET', f'/git/blobs/{item["sha"]}')
                source = base64.b64decode(blob['content']).decode('utf-8-sig')
                if re.search(r'\[\s*"' + re.escape(name) + r'"\s*\]\s*=', source):
                    raise ValueError('That name is already used by a bundled emote. Choose another name.')
        entries[name] = meta
        files = {f'Emotes/uploaded/{name}.tga': texture,
                 'UploadedEmotes.json': (json.dumps(entries, indent=2) + '\n').encode(),
                 'UploadedEmotes.lua': render(entries)}
        changes = []
        for path, content in files.items():
            blob = self.api('POST', '/git/blobs', json={
                'content': base64.b64encode(content).decode(), 'encoding': 'base64'})
            changes.append(dict(path=path, mode='100644', type='blob', sha=blob['sha']))
        new_tree = self.api('POST', '/git/trees', json={'base_tree': commit['tree']['sha'], 'tree': changes})
        new_commit = self.api('POST', '/git/commits', json={
            'message': f'{"Edit" if edit else "Add"} uploaded emote {name}', 'tree': new_tree['sha'], 'parents': [head]})
        # Non-forced update rejects a concurrent writer instead of losing their changes.
        self.api('PATCH', f'/git/refs/heads/{self.branch}', json={'sha': new_commit['sha'], 'force': False})
        return new_commit['html_url'], meta.get('trigger', f':uploaded_{name}:')

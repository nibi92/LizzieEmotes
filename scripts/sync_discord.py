"""Fetch custom server emojis with a bot token; generate isolated addon assets."""
import argparse
import io
import json
import os
from pathlib import Path
import re
import tempfile
import time

from PIL import Image, ImageOps
import requests

ROOT = Path(__file__).resolve().parents[1]


def fetch(url, token=None):
    headers = {'User-Agent': 'DiscordBot (https://github.com/nibi92/LizzieEmotes, 1.0)'}
    if token:
        headers['Authorization'] = 'Bot ' + token
    for attempt in range(5):
        response = requests.get(url, headers=headers, timeout=60, allow_redirects=False)
        if response.status_code == 429:
            delay = float(response.json().get('retry_after', 1))
            if not 0 <= delay <= 60:
                raise RuntimeError('Rate limit requires a longer wait; retry later')
            time.sleep(delay)
            continue
        if response.status_code >= 500:
            time.sleep(2 ** attempt)
            continue
        if response.status_code != 200:
            raise RuntimeError(f'Download failed: HTTP {response.status_code} (check bot membership/token)')
        return response.content
    raise RuntimeError('Download failed after five retries')


def convert(data, destination):
    # Fixed 64px frames, power-of-two sheet, at most 4096px high.
    # Resample timing uniformly because the addon uses a single frame rate.
    with Image.open(io.BytesIO(data)) as source:
        frames, durations = [], []
        for i in range(getattr(source, 'n_frames', 1)):
            if i >= 1000:
                raise ValueError('Emoji exceeds 1000 frames')
            source.seek(i)
            frames.append(ImageOps.contain(source.convert('RGBA'), (64, 64)))
            durations.append(max(20, source.info.get('duration', 100)))
    total = sum(durations)
    count = min(64, max(2, round(total / 40))) if len(frames) > 1 else 1
    height = 1 << (64 * count - 1).bit_length()
    sheet = Image.new('RGBA', (64, height))
    index, end = 0, durations[0]
    for i in range(count):
        instant = i * total / count
        while instant >= end and index < len(frames) - 1:
            index += 1
            end += durations[index]
        frame = frames[index]
        sheet.alpha_composite(frame, ((64 - frame.width) // 2, i * 64 + (64 - frame.height) // 2))
    sheet.save(destination, format='TGA')
    return dict(nFrames=count, frameWidth=64, frameHeight=64, imageWidth=64,
                imageHeight=height, framerate=round(count * 1000 / total, 6))


def sync(guild, token, root=ROOT):
    if not re.fullmatch(r'[0-9]{5,25}', guild):
        raise ValueError('Set DISCORD_GUILD_ID to your numeric server ID')
    if not token:
        raise ValueError('Set DISCORD_BOT_TOKEN in your environment or GitHub secrets')
    emojis = json.loads(fetch(f'https://discord.com/api/v10/guilds/{guild}/emojis', token))
    if not isinstance(emojis, list):
        raise ValueError('Unexpected Discord response')
    lines = ['-- Generated by scripts/sync_discord.py; do not edit.', 'local category = {}']
    used = set()
    # Complete every download/conversion before touching existing addon files.
    with tempfile.TemporaryDirectory(prefix='.discord-sync-', dir=root) as temporary:
        stage = Path(temporary)
        for emoji in sorted(emojis, key=lambda e: str(e['id'])):
            ident, name = str(emoji['id']), emoji['name']
            if not re.fullmatch(r'[0-9]{5,25}', ident) or not re.fullmatch(r'[A-Za-z0-9_]+', name or ''):
                raise ValueError('Discord returned an invalid emoji ID/name')
            key = f':discord_{name}:'
            if key in used:
                key = f':discord_{name}_{ident}:'
            used.add(key)
            ext = 'gif' if emoji.get('animated') else 'png'
            data = fetch(f'https://cdn.discordapp.com/emojis/{ident}.{ext}?size=64')
            meta = convert(data, stage / f'{ident}.tga')
            texture = f'Interface\\AddOns\\LizzieEmotes\\Emotes\\discord\\{ident}.tga'
            # JSON quoting is compatible with Lua for these validated ASCII strings.
            qkey, qpath = json.dumps(key), json.dumps(texture)
            lines += [f'TwitchEmotes_defaultpack[{qkey}] = {json.dumps(texture + ":28:28")}',
                      f'TwitchEmotes_emoticons[{qkey}] = {qkey}']
            if meta['nFrames'] > 1:
                values = ', '.join(f'{k} = {v}' for k, v in meta.items())
                lines.append(f'TwitchEmotes_animation_metadata[{qpath}] = {{{values}}}')
            lines += [f'category[#category + 1] = {qkey}',
                      'if #category == 45 then',
                      '    TwitchEmotes_dropdown_options[#TwitchEmotes_dropdown_options + 1] = category',
                      '    category = {}', 'end']
        lines += ['if #category > 0 then',
                  '    TwitchEmotes_dropdown_options[#TwitchEmotes_dropdown_options + 1] = category', 'end', '']
        generated = stage / 'DiscordEmotes.lua'
        generated.write_text('\n'.join(lines), encoding='utf-8')
        target = root / 'Emotes' / 'discord'
        target.mkdir(parents=True, exist_ok=True)
        for asset in stage.glob('*.tga'):
            asset.replace(target / asset.name)
        generated.replace(root / 'DiscordEmotes.lua')
        # Older textures are kept; deleted/renamed emojis disappear from generated Lua.
    print(f'Synced {len(emojis)} Discord emojis')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--guild-id', default=os.environ.get('DISCORD_GUILD_ID', ''))
    args = parser.parse_args()
    sync(args.guild_id, os.environ.get('DISCORD_BOT_TOKEN', ''))
